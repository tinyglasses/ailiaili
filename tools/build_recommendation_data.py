"""Derive browser recommendation inputs from the public daily metrics and config.

No database, credentials, network or original run directory is needed. Counts stay
daily (not lifetime totals), so the browser can enforce each visit's time boundary.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path

import yaml

FIELDS = (
    'impressions', 'clicks', 'completed_follow_opportunities', 'new_follows',
    'completed_post_click_opportunities', 'triples',
)
CONFIG_KEYS = (
    'homepage_size', 'cold_impression_target', 'cold_ratio', 'explore_ratio',
    'max_videos_per_creator', 'age_half_life_days', 'interest_slots_max', 'following_slots_max',
)


def text_sha256(path: Path) -> str:
    """Keep text source fingerprints stable across Git checkout line endings."""
    return hashlib.sha256(path.read_text(encoding='utf-8').encode('utf-8')).hexdigest()


def build(root: Path) -> dict:
    world = json.loads((root / 'data/world.json').read_text(encoding='utf-8'))
    works = world['community']['catalog']['works']
    config_path = root / 'configs/reference/world.yaml'
    config = yaml.safe_load(config_path.read_text(encoding='utf-8'))
    totals: dict[str, dict[int, list[int]]] = {key: {} for key in sorted(works)}
    metrics_path = root / 'data/daily_metrics.csv'
    with metrics_path.open(encoding='utf-8-sig', newline='') as stream:
        for row in csv.DictReader(stream):
            if row['entity_type'] != 'video':
                continue
            key, day = row['entity_id'], int(row['simulation_day'])
            if row['run_id'] != world['run_id'] or key not in works:
                raise ValueError('Metrics and catalog must belong to the same public run')
            if not 0 <= day <= config['days']:
                raise ValueError('Metric day outside the published world')
            values = [int(row[field]) for field in FIELDS]
            if min(values) < 0:
                raise ValueError('Negative event counts are not supported')
            current = totals[key].setdefault(day, [0] * len(FIELDS))
            for index, value in enumerate(values):
                current[index] += value
    result = {
        'schema': 'ailiaili-recommendation-inputs-v1', 'run_id': world['run_id'],
        'max_day': config['days'], 'columns': list(FIELDS),
        'rules': {key: config[key] for key in CONFIG_KEYS},
        'catalog': {key: [w['creator_id'], w['category'], w['published_day']]
                    for key, w in sorted(works.items())},
        'daily': {key: [[day, *values] for day, values in sorted(days.items()) if any(values)]
                  for key, days in totals.items()},
        'sources': {
            'metrics': 'data/daily_metrics.csv',
            'metrics_sha256': text_sha256(metrics_path),
            'config': 'configs/reference/world.yaml',
            'config_sha256': text_sha256(config_path),
            'text_hash_format': 'utf8-lf-v1',
            'rule_implementation': 'src/ailiaili/recommendation.py',
        },
    }
    canonical = json.dumps(result, ensure_ascii=False, sort_keys=True, separators=(',', ':'))
    result['revision'] = hashlib.sha256(canonical.encode('utf-8')).hexdigest()[:16]
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    result = build(args.root)
    target = args.root / 'site/recommendation-data.js'
    payload = json.dumps(result, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')
    target.write_text('// Generated by tools/build_recommendation_data.py; do not edit.\n'
                      'globalThis.AiliAiliRecommendationData=' + payload + ';\n', encoding='utf-8', newline='\n')
    print(json.dumps({'videos': len(result['catalog']), 'revision': result['revision'],
                      'bytes': target.stat().st_size}))


if __name__ == '__main__':
    main()
